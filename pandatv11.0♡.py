def convert_to_font(text, style):
    if style not in FONT_STYLES:
        return text
    style_chars = FONT_STYLES[style]['chars']
    result = []
    for char in text:
        if 'a' <= char <= 'z':
            idx = ord(char) - ord('a') + 26
            result.append(style_chars[idx] if idx < len(style_chars) else char)
        elif 'A' <= char <= 'Z':
            idx = ord(char) - ord('A')
            result.append(style_chars[idx] if idx < len(style_chars) else char)
        else:
            result.append(char)
    return ''.join(result)

