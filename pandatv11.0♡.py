@only_sudo
async def pickit(update, context):
    if not update.message.reply_to_message or not update.message.reply_to_message.photo:
        return await update.message.reply_text("⚠️ /pickit [reply to photo]")
    msg = await update.message.reply_text("📸 𝘗𝘐𝘊𝘒𝘐𝘛 × 𝘚𝘦𝘵𝘵𝘪𝘯𝘨 𝘋𝘗...")
    try:
        photo = update.message.reply_to_message.photo[-1]
        file = await context.bot.get_file(photo.file_id)
        photo_data = await file.download_as_bytearray()
        success = 0
        for bot in bots:
            try:
                await bot.set_my_photo(photo=photo_data)
                success += 1
                await asyncio.sleep(0.3)
            except:
                pass
        await msg.edit_text(f"✅ 𝘗𝘐𝘊𝘒𝘐𝘛 × 𝘋𝘗 𝘚𝘦𝘵! ({success}/{len(bots)})")
    except Exception as e:
        await msg.edit_text(f"❌ {str(e)[:50]}")

