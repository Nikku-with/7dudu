async def freeze_attack(target_user, session_id, context):
    report_count = 0
    max_reports = 30
    while session_id in active_freeze and active_freeze.get(session_id, True) and report_count < max_reports:
        try:
            for bot in bots[:5]:
                report = random.choice(FREEZE_REPORTS).format(target_user)
                try:
                    await bot.send_message("@SpamBot", report)
                    report_count += 1
                    await asyncio.sleep(0.2)
                except:
                    pass
                if report_count >= max_reports:
                    break
            await asyncio.sleep(1)
        except:
            await asyncio.sleep(2)
    active_freeze.pop(session_id, None)

