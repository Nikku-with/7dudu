async def button_callback(update, context):
    query = update.callback_query
    await query.answer()
    
    menus = {
        "attacks": ATTACKS_MENU,
        "admin": ADMIN_MENU,
        "tools": TOOLS_MENU,
        "fun": FUN_MENU,
        "settings": SETTINGS_MENU,
        "status": STATUS_MENU,
        "misc": MISC_MENU,
    }
    
    if query.data in menus:
        await query.edit_message_text(menus[query.data], reply_markup=get_back_button())
    elif query.data == "main":
        if os.path.exists(MENU_MEDIA_PATH) and os.path.getsize(MENU_MEDIA_PATH) > 0:
            try:
                if MENU_MEDIA_TYPE == "video":
                    with open(MENU_MEDIA_PATH, 'rb') as video:
                        await query.edit_message_media(
                            media=InputMediaVideo(media=video, caption=MENU_CAPTION or MAIN_MENU),
                            reply_markup=get_main_menu()
                        )
                else:
                    with open(MENU_MEDIA_PATH, 'rb') as photo:
                        await query.edit_message_media(
                            media=InputMediaPhoto(media=photo, caption=MENU_CAPTION or MAIN_MENU),
                            reply_markup=get_main_menu()
                        )
                return
            except:
                pass
        await query.edit_message_text(MAIN_MENU, reply_markup=get_main_menu())

