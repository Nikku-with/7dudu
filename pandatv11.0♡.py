#  🤖 MULTI-BOT SYSTEM FUNCTIONS
# ═══════════════════════════════════════════════════════════════
async def add_bot(token):
    try:
        app = build_app(token)
        apps.append(app)
        bots.append(app.bot)
        await app.initialize()
        await app.start()
        await app.updater.start_polling()
        return True
    except Exception as e:
        print(f"❌ Failed to add bot: {e}")
        return False

